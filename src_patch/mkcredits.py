"""COMMUNITY CREDITS in the GHOSTS'N GOBLINS title's lettering (drawn here, letter by letter, on its grid:
8 px wide strokes of 3, 16 rows, rounded top corners; light grey on top, red from row 10 with drips over
rows 7-9, a blue shadow one and two pixels down-right; pens 9, 7 and 1 of the title's palette line 0).
Writes the tiles and the 32 x 3 map for boot.c's credits screen.

usage: mkcredits.py <out.inc>"""
import sys

G = {
    'C': ['.######.', '########', '###..###', '###..###', '###..###', '###.....', '###.....', '###.....',
          '###.....', '###.....', '###.....', '###..###', '###..###', '###..###', '########', '.######.'],
    'O': ['.######.', '########'] + ['###..###'] * 12 + ['########', '.######.'],
    'M': ['###...###', '####.####', '#########', '###.#.###'] + ['###...###'] * 12,
    'U': ['###..###'] * 14 + ['########', '.######.'],
    'N': ['###...###', '###...###', '####..###', '####..###', '####..###', '#####.###', '#####.###',
          '#########', '#########', '###.#####', '###.#####', '###..####', '###..####', '###..####',
          '###...###', '###...###'],
    'I': ['###'] * 16,
    'T': ['#########', '#########'] + ['...###...'] * 14,
    'Y': ['###...###'] * 5 + ['####.####', '.#######.', '..#####..'] + ['...###...'] * 8,
    'R': ['#######.', '########', '###..###', '###..###', '###..###', '###..###', '########', '#######.',
          '###.###.', '###.###.', '###..###', '###..###', '###..###', '###..###', '###..###', '###..###'],
    'E': ['########', '########', '###.....', '###.....', '###.....', '###.....', '#######.', '#######.',
          '###.....', '###.....', '###.....', '###.....', '###.....', '###.....', '########', '########'],
    'D': ['######..', '#######.'] + ['###..###'] * 12 + ['#######.', '######..'],
    'S': ['.######.', '########', '###..###', '###..###', '###..###', '###..###', '.###....', '..###...',
          '...###..', '....###.', '###..###', '###..###', '###..###', '###..###', '########', '.######.'],
}
DRIP = [8, 7, 9, 8, 10, 7, 9, 8, 7, 10, 8, 9]       # the row each column's red starts at
GREY, RED, BLUE = 9, 7, 1
TEXT, W, H, TOP = 'COMMUNITY CREDITS', 256, 24, 3


def render():
    ink = [[0] * W for _ in range(H)]
    widths = [len(G[c][0]) if c != ' ' else 6 for c in TEXT]
    x = (W - (sum(widths) + 3 * (len(TEXT) - 1) + 2)) // 2
    for c, w in zip(TEXT, widths):
        if c != ' ':
            for y, row in enumerate(G[c]):
                for i, v in enumerate(row):
                    if v == '#':
                        ink[TOP + y][x + i] = 1
        x += w + 3
    g = [[0] * W for _ in range(H)]
    for y in range(H):
        for x in range(W):
            if ink[y][x]:
                g[y][x] = RED if y - TOP >= DRIP[x % len(DRIP)] else GREY
    for y in range(H):
        for x in range(W):
            if not ink[y][x] and ((y >= 1 and x >= 1 and ink[y - 1][x - 1]) or (y >= 2 and x >= 2 and ink[y - 2][x - 2])):
                g[y][x] = BLUE
    return g


def main(out):
    g = render()
    tiles, index, nt = [bytes(32)], {bytes(32): 0}, []
    for ty in range(H // 8):
        for tx in range(W // 8):
            t = bytes((g[ty * 8 + y][tx * 8 + x] << 4) | g[ty * 8 + y][tx * 8 + x + 1]
                      for y in range(8) for x in range(0, 8, 2))
            if t not in index:
                index[t] = len(tiles)
                tiles.append(t)
            nt.append(index[t])
    with open(out, 'w') as f:
        f.write('/* generated by mkcredits.py: COMMUNITY CREDITS in the title lettering */\n')
        f.write('#define CRED_NT %d\n' % len(tiles))
        f.write('static const u16 cred_tiles[%d] = {\n' % (len(tiles) * 16))
        for t in tiles:
            f.write('    ' + ', '.join('0x%04X' % (t[i] << 8 | t[i + 1]) for i in range(0, 32, 2)) + ',\n')
        f.write('};\nstatic const u8 cred_map[%d] = {\n' % len(nt))
        for r in range(H // 8):
            f.write('    ' + ', '.join(str(v) for v in nt[r * 32:(r + 1) * 32]) + ',\n')
        f.write('};\n')


if __name__ == '__main__':
    main(sys.argv[1])
