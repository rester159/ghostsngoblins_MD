#!/usr/bin/env python3
"""Arcade art the port lacks, converted from the arcade's own graphics ROMs
(MAME set `gng`: sprites gg12-gg17, 4bpp 16x16; bg tiles gg6-gg11, 3bpp 16x16;
decoding as tools/arcade/gng.py's renderer) into Genesis 4bpp tiles and frame
tables, written as C to build/art.inc (included by bossart.c).

usage: mkart.py <rom dir> <out.inc>

Colours: each group is drawn with a port palette line that is already loaded
at those moments (the port's CRAM, listed below as read from the running
port); each arcade pen goes to the nearest colour of that line (RGB distance),
except where the port's own conversion of the same character already chose
(the Satan: the pens of its wings and body as in the port's own Satan tiles,
$2552F4, so the new poses match the old ones).

A 16x16 arcade sprite becomes a 2x2 Genesis sprite piece: 4 tiles in the
VDP's column order (top left, bottom left, top right, bottom right)."""
import os
import sys

romdir, dst = sys.argv[1], sys.argv[2]
rd = lambda n: open(os.path.join(romdir, n), 'rb').read()
FF = b'\xff' * 0x4000
SPR = b''.join((rd('gg17.bin'), rd('gg16.bin'), rd('gg15.bin'), FF, rd('gg14.bin'), rd('gg13.bin'), rd('gg12.bin'), FF))
TIL = b''.join(rd(n) for n in ('gg11.bin', 'gg10.bin', 'gg9.bin', 'gg8.bin', 'gg7.bin', 'gg6.bin'))


def spr_pen(code, x, y):
    o = code * 64 + y * 2 + (32 if x >= 8 else 0) + ((x & 7) >> 2)
    bit = 3 - (x & 3)
    lo, hi = SPR[o], SPR[0x10000 + o]
    return ((lo >> (bit + 4)) & 1) | (((lo >> bit) & 1) << 1) | (((hi >> (bit + 4)) & 1) << 2) | (((hi >> bit) & 1) << 3)


def til_pen(code, x, y):
    o = code * 32 + y + (16 if x >= 8 else 0)
    bit = 7 - (x & 7)
    return (((TIL[o] >> bit) & 1) | (((TIL[0x8000 + o] >> bit) & 1) << 1) | (((TIL[0x10000 + o] >> bit) & 1) << 2))


def rgb(s):
    return tuple(int(s[i:i + 2], 16) for i in (0, 2, 4))


def nearest(line, colour):
    """index 1-15 of the nearest colour of a port palette line"""
    return min(range(1, 16), key=lambda i: sum((a - b) ** 2 for a, b in zip(line[i], colour)))


def penmap(arc_pal, line, transparent, fixed=None):
    m = {transparent: 0}
    for p in range(len(arc_pal)):
        if p != transparent:
            m[p] = nearest(line, arc_pal[p])
    m.update(fixed or {})
    return m


# --- palettes ---------------------------------------------------------------
# the port's line 0 in stages 5 and 6 (Arthur's line, also the Satan's)
PORT_L0_S56 = [rgb(c) for c in (
    '000000 000000 740000 ce0000 573400 903400 745700 ce7400 909000 343474 ac9074 747490 ceac90 0074ac 9090ac acacce'
    .split())]
# arcade sprite palettes in play ($3800/$3900 entries $40 + 16 * colour), stage 5
ARC_SPR = {c: [rgb(x) for x in s.split()] for c, s in {
    1: 'cc5500 000000 005500 007700 009900 66bb66 bbbbbb 888888 664400 886644 997755 bb9966 550000 880000 aa0000 000000',
    2: 'aa77ee 000000 660000 880000 aa0000 aa5500 bb9966 997755 555555 777777 999999 bbbbbb 550088 663399 8855cc 000000',
    3: 'bbbbbb 000000 333388 4455aa 5577bb 6699cc aa9977 887755 660000 880000 aa0000 bb5500 555555 777777 999999 000000',
}.items()}
# the pens of the port's own Satan tiles (arcade colour 2 -> line 0)
SATAN_FIXED = {1: 1, 2: 2, 3: 2, 4: 3, 5: 7, 7: 0xA, 8: 9, 9: 0xB, 0xA: 0xE, 0xB: 0xF, 0xC: 9, 0xD: 0xB, 0xE: 0xE}
PM_SATAN = penmap(ARC_SPR[2], PORT_L0_S56, 15, SATAN_FIXED)
PM_BURST = penmap(ARC_SPR[1], PORT_L0_S56, 15)
PM_STAR = penmap(ARC_SPR[3], PORT_L0_S56, 15)


def piece(code, pm):
    """a 16x16 sprite as 4 Genesis tiles (64 words); None when it's blank"""
    px = [[pm[spr_pen(code, x, y)] for x in range(16)] for y in range(16)]
    if not any(v for r in px for v in r):
        return None
    words = []
    for tx, ty in ((0, 0), (0, 1), (1, 0), (1, 1)):
        for y in range(8):
            r = px[ty * 8 + y][tx * 8:tx * 8 + 8]
            words += [(r[0] << 12) | (r[1] << 8) | (r[2] << 4) | r[3], (r[4] << 12) | (r[5] << 8) | (r[6] << 4) | r[7]]
    return words


out = ['/* generated by mkart.py from the arcade graphics ROMs (rom/gg12-gg17, gg6-gg11) */']


INTRO_SECT = ('isc_tiles', 'isc_planeb', 'ib_tiles', 'ib_lists', 'hud_tiles')   # the opening's bulk: in the
                                                    # .intro region ($350000, link.ld), the code region is full


def emit_words(name, words):
    sect = ' section(".intro.opening"),' if name in INTRO_SECT else ''
    out.append('static const u16 %s[%d] __attribute__((%s aligned(2))) = {' % (name, len(words), sect))
    for i in range(0, len(words), 16):
        out.append('    ' + ', '.join('0x%04X' % w for w in words[i:i + 16]) + ',')
    out.append('};')


# --- the Satan (stages 5 and 6) -------------------------------------------
# Frames as the arcade's scripts list them, facing right: 9 codes, column by
# column from the left, each from the bottom up (the order of $906B's entries:
# fly $4CDE, wings closed $4CFC, hovering with the wings open $4C9F (3 poses);
# the burst $5B89 (size class 3: 2x2) and $5B24 (3x3)). Facing left the
# arcade draws the columns in the other order, each piece mirrored ($4CD1 ...).
G3 = [(-24 + 16 * c, 24 - 16 * r) for c in range(3) for r in range(3)]     # 3x3: dx, dy (port: screen y = sy + dy)
G2 = [(-16 + 16 * c, 16 - 16 * r) for c in range(2) for r in range(2)]     # 2x2
SAT_ART = [   # (name, codes, grid, pen map)
    ('fly', [0x2B0, 0x2A8, 0x2A0, 0x2B1, 0x2A9, 0x2A1, 0x2B2, 0x2AA, 0x2A2], G3, PM_SATAN),
    ('wrap', [0x2B3, 0x2AB, 0x2A3, 0x2B4, 0x2AC, 0x2A4, 0x2B5, 0x2AD, 0x2A5], G3, PM_SATAN),
    ('flapA', [0x290, 0x288, 0x280, 0x291, 0x289, 0x281, 0x292, 0x28A, 0x282], G3, PM_SATAN),
    ('flapB', [0x293, 0x28B, 0x283, 0x294, 0x28C, 0x284, 0x295, 0x28D, 0x285], G3, PM_SATAN),
    ('flapC', [0x296, 0x28E, 0x286, 0x297, 0x28F, 0x287, 0x29A, 0x299, 0x298], G3, PM_SATAN),
    ('burst1', [0x2BE, 0x2BC, 0x2BF, 0x2BD], G2, PM_BURST),
    ('burstA', [0x2B7, 0x2B7, 0x29B, 0x2A6, 0x2A6, 0x2A6, 0x270, 0x270, 0x278], G3, PM_BURST),
    ('burstB', [0x2B8, 0x2B8, 0x29C, 0x2A7, 0x2A7, 0x2A7, 0x271, 0x271, 0x279], G3, PM_BURST),
    ('burstC', [0x2B9, 0x2B9, 0x29D, 0x2AE, 0x2AE, 0x2AE, 0x272, 0x272, 0x27A], G3, PM_BURST),
]
# p[30] frame numbers: 1-4 and 5 as the port's (fly left/right, wings closed
# left/right, the score); then the new ones
SAT_FRAMES = [None, ('fly', 1), ('fly', 0), ('wrap', 1), ('wrap', 0), 'score',
              ('flapA', 1), ('flapA', 0), ('flapB', 1), ('flapB', 0), ('flapC', 1), ('flapC', 0),
              ('burst1', 0), ('burstA', 0), ('burstB', 0), ('burstC', 0)]
words, blocks = [], {}
for name, codes, grid, pm in SAT_ART:
    slots, uniq = [], []
    for c in codes:
        w = piece(c, pm)
        if w is None:
            slots.append(None)
            continue
        if w not in uniq:
            uniq.append(w)
        slots.append(uniq.index(w))
    blocks[name] = (len(words), len(uniq), slots, grid)
    for w in uniq:
        words += w
emit_words('sat_art', words)
out.append('typedef struct { s8 dx, dy; u8 slot, flip; } SatPiece;')
out.append('typedef struct { u16 art; u8 nart, npc; SatPiece pc[9]; } SatFrame;')
out.append('#define SAT_NFRAMES %d' % len(SAT_FRAMES))
out.append('static const SatFrame sat_frames[SAT_NFRAMES] = {')
for f in SAT_FRAMES:
    if f is None or f == 'score':
        out.append('    { 0xFFFF, 0, 0, {{0}} },' if f else '    { 0, 0, 0, {{0}} },')
        continue
    name, left = f
    art, nart, slots, grid = blocks[name]
    n = len(slots)
    pcs = []
    for k, (dx, dy) in enumerate(grid):
        src = k
        if left:                    # mirrored: the columns in the other order, each piece flipped
            rows = 3 if n == 9 else 2
            col, row = divmod(k, rows)
            src = (rows - 1 - col) * rows + row
        if slots[src] is None:
            continue
        pcs.append('{%d, %d, %d, %d}' % (dx, dy, slots[src], 8 if left else 0))
    out.append('    { %d, %d, %d, { %s } },  /* %s%s */' % (art, nart, len(pcs), ', '.join(pcs), name, ' left' if left else ''))
out.append('};')
out.append('#define SAT_ART_BLOCK(f) (sat_frames[f].art)')

# the Satan's shot: the star, sprites $1D7/$1DF (colour 3), 4 frames each
emit_words('star_art', piece(0x1D7, PM_STAR) + piece(0x1DF, PM_STAR))

# --- stage 5's skulls and Petite Devils (colour 3, drawn with line 0) --------
# The port's own conversions of the same characters fix most pens: its skull
# tiles ($4A0-$4B3: $A7, $A2-$A5) and its devil frames ($10D526: $F0-$FC).
SKULL_FIXED = {0: 0xF, 1: 1, 2: 9, 3: 0xD, 4: 0xB, 5: 0xE, 0xC: 9, 0xD: 0xB, 0xE: 0xE}
DEVIL_FIXED = {0: 0xF, 1: 1, 2: 9, 3: 0xB, 4: 0xB, 5: 0xE, 6: 0xA, 8: 2, 9: 2, 0xA: 3, 0xB: 7}
PM_SKULL = penmap(ARC_SPR[3], PORT_L0_S56, 15, SKULL_FIXED)
PM_DEVIL = penmap(ARC_SPR[3], PORT_L0_S56, 15, DEVIL_FIXED)
# the skull standing up (class 3, $CE1A: A8 A0 A9 A1, AA A2 AB A3, AC A4 AD A5; the
# port has A2-A5): A0 A1 A8 A9 AA AB AC AD, in tiles $524-$543
emit_words('skull_art', sum((piece(c, PM_SKULL) for c in (0xA0, 0xA1, 0xA8, 0xA9, 0xAA, 0xAB, 0xAC, 0xAD)), []))
# the fireball ($F7) and the carrier's wing poses with it ($FD-$FF)
emit_words('fire_art', piece(0xF7, PM_DEVIL))
emit_words('pd_art', sum((piece(c, PM_DEVIL) for c in (0xFD, 0xFE, 0xFF)), []))

# --- stage 2's windows (the devils' $B457: bg tiles $2F0-$2FF, colour 7) -------
# Each step writes 2x2 bg tiles: $Fn top left, $Fn+8 below it, $Fn+1 and $Fn+9
# to the right ($B495 opening F0 F2 F4 F6, $B4A9 closing F6 F4 F2 F0). The port
# draws stage 2's bg on plane B with line 3; its closed windows (F0, from its own
# conversion) map the pens 0 1 2 3 4 5 6 to 1 4 5 6 6 A A (pen 7, black, unused
# there, to 1). Each open pose is 16 tiles, row by row (4 x 4 cells).
PM_WIN = {0: 1, 1: 4, 2: 5, 3: 6, 4: 6, 5: 0xA, 6: 0xA, 7: 1}


def bg_cells(code):
    """a 16x16 bg tile as 2x2 cells: [[top left, top right], [bottom left, bottom right]] of 16 words"""
    cells = [[None, None], [None, None]]
    for qy in range(2):
        for qx in range(2):
            w = []
            for y in range(8):
                r = [PM_WIN[til_pen(code, qx * 8 + x, qy * 8 + y)] for x in range(8)]
                w += [(r[0] << 12) | (r[1] << 8) | (r[2] << 4) | r[3], (r[4] << 12) | (r[5] << 8) | (r[6] << 4) | r[7]]
            cells[qy][qx] = w
    return cells


words = []
for n in (0xF2, 0xF4, 0xF6):
    tl, tr, bl, br = (bg_cells(0x200 + c) for c in (n, n + 1, n + 8, n + 9))
    for row in range(4):
        left, right = (tl, tr) if row < 2 else (bl, br)
        for col in range(4):
            words += (left if col < 2 else right)[row & 1][col & 1]
emit_words('win_art', words)


# --- the opening (opening.c `intro_scene`; build/intro_art.inc) -----------------------------------
# After Start the arcade draws stage 1's graveyard (camera 0, the HUD's top two
# rows) with Arthur sitting in his boxers, the princess and the armour, and
# fades its bg palettes twice before it goes black. The scene is taken from the
# arcade itself: tools/arcade/gng.py run from power-on (coin at frame 700,
# Start at 800, as tools/lockstep does) gives the bg and fg RAM and the sprite
# list (frame 870), the palettes of the three phases (806, 871, 935), Arthur's
# second pose (955) and the Satan's cloak over the graveyard (993 and 996, the
# first frames of its blinking). Plane B holds the bg (arcade 16x16 tiles as
# 2x2 cells; black, pen 0, is the backdrop), the window the HUD chars (its top
# two rows), sprites the pieces. Each arcade palette (bg 0-7, sprite colours,
# fg 0-15) goes whole into one of the 4 lines; the lines are packed from the
# colours of all three phases (sprites and HUD don't fade).
#
# VRAM: the port's black part ($E0C) uses tiles $000-$550 and plane B at
# $C000; opening.c loads both while the graveyard shows, so the graveyard
# keeps out of them: its tiles go to $551-$5FF, $6C0-$6FF ($D800, after the
# window), $770-$77F and $794-$7D5 (free in both parts; a sprite piece's 4
# tiles stay in one block), its bg to plane B at $E000 (plane A shows the
# same plane), the HUD to the window ($D000, 32 cells a row in H32).
# $7D6-$7DF: the black part's digits for the top score (opening.c makes them
# from the arcade's chars, CHR_DIGITS).
ISC_REGIONS = [(0x551, 0x600), (0x6C0, 0x700), (0x770, 0x780), (0x794, 0x7D6)]
ISC_EDIG = 0x7D6
IB_FRAMES = 1319 - 999                              # the black part (arcade frames 999-1318)
IB_TILE0 = 0x001                                    # its sprite tiles (tiles $001-$550 are free then)


def intro_scene():
    global out
    main_out, out = out, ['/* generated by mkart.py: the opening\'s graveyard (opening.c) */']
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tools', 'arcade'))
    from gng import GnG
    g = GnG(romdir); m = g.mem
    pal, snap = {}, {}
    blk_spr = {}                                    # the black part: the sprite list of every frame
    hud = {}                                        # the HUD on black after it: fg and palette
    for f in range(1, 1360):
        g.set_inputs(0x40 if 700 <= f <= 710 else (1 if 800 <= f <= 805 else 0), 0, 0)
        g.run_frame()
        if f in (806, 871, 935, 1000):
            pal[f] = g.palette()
        if f in (1319, 1321, 1340):
            hud[f] = dict(fg=bytes(m[0x2000:0x2800]), pal=g.palette())
        if f in (870, 955, 993, 996) or 999 <= f < 999 + IB_FRAMES:
            b = g.spritebuf; sp = []
            for o in range(0x200 - 4, -1, -4):          # back to front, as the renderer
                attr = b[o + 1]; code = b[o] + ((attr << 2) & 0x300)
                x = b[o + 3] - (0x100 if attr & 1 else 0); y = b[o + 2] - 16
                if (0 if f < 999 else -16) < y < 224 and -16 < x < 256:
                    sp.append((code, (attr >> 4) & 3, attr & 4, attr & 8, x, y))
            if f >= 999:
                blk_spr[f] = sp
                if f == 999:
                    assert bytes(m[0x2000 + 64:0x2000 + 128]) == snap[870]['fg'][64:128]   # the HUD's rows as the graveyard's
                continue
            snap[f] = dict(bg=bytes(m[0x2800:0x3000]), fg=bytes(m[0x2000:0x2800]), spr=sp, scroll=list(g.scroll))
    # After the second clear the arcade shows the graveyard's bg in the final room's bg palette for its first frames
    # (the room's palette stays until the scene's 9th frame, the bg is written on its 4th): the final room reached
    # as arc_start.py does, the end forced (<$7F = 1, <$08 = 2, <$0B = 0), that palette taken 6 frames into the scene
    # (the black part's first frame, the first with its opening list, is the scene's frame 193)
    g = GnG(romdir); m = g.mem; t = None
    for f in range(1, 4000):
        if 820 <= f < 1320 and f % 10 == 0: m[0x72] = 6; m[0x81] = 0
        g.set_inputs(0x40 if 700 <= f <= 710 else (1 if 800 <= f <= 805 else 0), 0, 0); g.run_frame()
        if t is None and f > 1320 and (m[0x506] << 8 | m[0x507]) > 200 and (m[0x9C] or m[0x9D] or m[0x9E] or m[0x9F]): t = f + 30
        if t and f == t: break
    assert t, 'final room not reached'
    m[0x7F] = 1; m[0x08] = 2; m[0x0B] = 0
    ph = []
    for k in range(4000):
        g.set_inputs(0, 0, 0); g.run_frame(); ph.append(g.palette())
        b = g.spritebuf; sp = []
        for o in range(0x200 - 4, -1, -4):
            attr = b[o + 1]; code = b[o] + ((attr << 2) & 0x300)
            x = b[o + 3] - (0x100 if attr & 1 else 0); y = b[o + 2] - 16
            if -16 < y < 224 and -16 < x < 256: sp.append((code, (attr >> 4) & 3, attr & 4, attr & 8, x, y))
        if sp == blk_spr[999]: break
    assert sp == blk_spr[999], 'the second clear\'s black part not found'
    pal_room = ph[k - 193 + 6]
    assert pal_room[:0x40] != pal[806][:0x40] and ph[k - 193 + 9][:0x40] == pal[806][:0x40]
    assert snap[870]['scroll'] == [0, 0, 0, 0]
    assert snap[993]['spr'] == snap[996]['spr']
    phases = (806, 871, 935)
    LV = [0, 52, 87, 116, 144, 172, 206, 255]       # Genesis levels (as tools/headless/vdp.py)
    q = lambda c: tuple(min(range(8), key=lambda i: abs(LV[i] - v)) for v in c)
    cram = lambda c: c[0] << 1 | c[1] << 5 | c[2] << 9
    bg, fg = snap[870]['bg'], snap[870]['fg']
    # what's on the screen
    cells = []          # (cx, cy, code, attr)
    for cy in range(1, 15):
        for cx in range(16):
            i = cx * 32 + cy
            cells.append((cx, cy, bg[i] | ((bg[0x400 + i] & 0xC0) << 2), bg[0x400 + i]))
    chars = []          # (tx, ty, code, attr) of the HUD rows
    for ty in range(2, 30):
        for tx in range(32):
            i = ty * 32 + tx
            code = fg[i] | ((fg[0x400 + i] & 0xC0) << 2)
            if any(((CHR[code * 16 + k] >> 4) & (CHR[code * 16 + k] & 15)) != 15 for k in range(16)):
                chars.append((tx, ty, code, fg[0x400 + i]))
    assert all(ty in (2, 3) for _, ty, _, _ in chars)
    # the top score: 8 digits at row 3, columns 12-19 ($D0-$D3), chars 0-9
    top_attr = fg[0x400 + 3 * 32 + 19]
    assert fg[3 * 32 + 19] == 0 and top_attr & 0xC0 == 0
    sprs = {f: snap[f]['spr'] for f in (870, 955, 993)}
    # colour keys: (kind, palette, pen) -> the colour in each phase
    groups = {}
    def key_col(kind, pl, pen):
        if kind == 'bg': return tuple(q(pal[f][pl * 8 + pen]) for f in phases)
        if kind == 'spr': return tuple(q(pal[806][0x40 + pl * 16 + pen]) for f in phases)
        return tuple(q(pal[806][0x80 + pl * 4 + pen]) for f in phases)
    for cx, cy, code, attr in cells:
        for y in range(16):
            for x in range(16):
                pen = til_pen(code, x, y)
                if pen: groups.setdefault(('bg', attr & 7), set()).add(pen)
    for f in sprs:
        for code, col, hf, vf, x, y in sprs[f]:
            for yy in range(16):
                for xx in range(16):
                    pen = spr_pen(code, xx, yy)
                    if pen != 15: groups.setdefault(('spr', col), set()).add(pen)
    for tx, ty, code, attr in chars + [(0, 0, d, top_attr) for d in range(10)]:
        for k in range(64):
            pen = chr_pen(code, k & 7, k >> 3)
            if pen != 3: groups.setdefault(('fg', attr & 15), set()).add(pen)
    black = ((0, 0, 0),) * 3
    lines = [[] for _ in range(4)]                  # colour vectors per line (index = position + 1)
    gline = {}
    for gk in sorted(groups, key=lambda k: -len(groups[k])):
        cols = set(key_col(gk[0], gk[1], pen) for pen in groups[gk]) - ({black} if gk[0] == 'bg' else set())
        best = None
        for li in range(4):
            new = len(cols - set(lines[li]))
            if len(lines[li]) + new <= 15 and (best is None or new < best[0]):
                best = (new, li)
        assert best, 'intro palette doesn\'t fit'
        li = best[1]
        for c in sorted(cols - set(lines[li])):
            lines[li].append(c)
        gline[gk] = li
    def idx(kind, pl, pen):
        c = key_col(kind, pl, pen)
        if kind == 'bg' and c == black: return 0
        return lines[gline[(kind, pl)]].index(c) + 1
    def tw(px):
        w = []
        for r in px:
            w += [(r[0] << 12) | (r[1] << 8) | (r[2] << 4) | r[3], (r[4] << 12) | (r[5] << 8) | (r[6] << 4) | r[7]]
        return w
    # tiles (linear; mapped to VRAM below)
    tiles = [[0] * 16]
    blocks = set()                                  # linear starts of sprite pieces (4 tiles together)
    def tile(px):
        w = tw(px)
        if w not in tiles: tiles.append(w)
        return tiles.index(w)
    planeb = [0] * (32 * 28)
    for cx, cy, code, attr in cells:
        li = gline.get(('bg', attr & 7), 0)
        for qy in range(2):
            for qx in range(2):
                pen = lambda x, y: til_pen(code, qx * 8 + (7 - x if attr & 0x10 else x), qy * 8 + (7 - y if attr & 0x20 else y))
                px = [[idx('bg', attr & 7, pen(x, y)) if pen(x, y) else 0 for x in range(8)] for y in range(8)]
                qxx = 1 - qx if attr & 0x10 else qx
                qyy = 1 - qy if attr & 0x20 else qy
                planeb[(cy * 2 - 2 + qyy) * 32 + cx * 2 + qxx] = (li << 13) | tile(px)
    def chr_cell(code, attr):
        li = gline[('fg', attr & 15)]
        cp = lambda x, y: chr_pen(code, 7 - x if attr & 0x10 else x, 7 - y if attr & 0x20 else y)
        px = [[0 if cp(x, y) == 3 else idx('fg', attr & 15, cp(x, y)) for x in range(8)] for y in range(8)]
        return 0x8000 | (li << 13) | tile(px)
    planea = [0] * (32 * 2)
