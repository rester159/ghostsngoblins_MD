"""Generate swap_ctx(buf): exchange the co-op context ranges (ctx_ranges in
p2.c) with buf, as straight-line code. Each range is moved in movem chunks of
up to seven longs at its fixed address (no loop or per-range setup), then a
trailing word if the length is 2 mod 4. buf holds the ranges back to back in
table order, exactly like the generic swap_fields it replaces.

usage: mkswap.py p2.c out.s
"""
import re
import sys

src = open(sys.argv[1]).read()
body = src[src.index('ctx_ranges[] = {'):src.index('};', src.index('ctx_ranges[] = {'))]
ranges = [(int(a, 16), int(n, 16)) for a, n in re.findall(r'\{ 0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+) \}', body)]
assert ranges and all(a % 2 == 0 and n % 2 == 0 for a, n in ranges)

GAME = ['%d0', '%d2', '%d3', '%d4', '%d5', '%d6', '%d7']   # chunk from the game's RAM
BUF = ['%d1', '%a0', '%a2', '%a3', '%a4', '%a5', '%a6']    # chunk from buf
out = ['| generated by mkswap.py from ctx_ranges in p2.c; do not edit',
       '    .text', '    .global swap_ctx', 'swap_ctx:',
       '    movem.l %d2-%d7/%a2-%a6,-(%sp)',
       '    movea.l 48(%sp),%a1                 | buf']
total = 0
for addr, n in ranges:
    a = 0xFF0000 + addr
    longs, word = divmod(n, 4)
    out.append('| $%06X, %d bytes' % (a, n))
    while longs:
        k = min(len(GAME), longs)
        g = '/'.join(GAME[:k]) if k > 1 else GAME[0]
        b = '/'.join(BUF[:k]) if k > 1 else BUF[0]
        out += ['    movem.l 0x%X,%s' % (a, g),
                '    movem.l (%%a1),%s' % b,
                '    movem.l %s,0x%X' % (b, a),
                '    movem.l %s,(%%a1)' % g,
                '    lea     %d(%%a1),%%a1' % (4 * k)]
        a += 4 * k
        longs -= k
    if word:
        out += ['    move.w  0x%X,%%d0' % a,
                '    move.w  (%%a1),0x%X' % a,
                '    move.w  %d0,(%a1)+']
    total += n
out += ['    movem.l (%sp)+,%d2-%d7/%a2-%a6', '    rts', '| %d bytes' % total]
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
