#!/usr/bin/env python3
"""ASCII $20-$7F from the arcade char ROM (gg1.bin, 8x8 2bpp, MAME gng layout)
-> Genesis 4bpp tiles as a C array. Pen 3 (background) becomes transparent;
pens 1, 2, 0 become colours 1 (face), 2 (shade), 3 (outline)."""
import sys
src, dst = sys.argv[1], sys.argv[2]
d = open(src, 'rb').read()
PEN = {3: 0, 1: 1, 2: 2, 0: 3}
words = []
for ch in range(0x20, 0x80):
    b = d[ch * 16:(ch + 1) * 16]
    for y in range(8):
        px = []
        for x in range(8):
            byte = b[y * 2 + x // 4]; bit = 3 - (x % 4)
            px.append(PEN[((byte >> bit) & 1) | (((byte >> (bit + 4)) & 1) << 1)])
        words.append((px[0] << 12) | (px[1] << 8) | (px[2] << 4) | px[3])
        words.append((px[4] << 12) | (px[5] << 8) | (px[6] << 4) | px[7])
with open(dst, 'w') as f:
    f.write('/* generated by mkfont.py from rom/gg1.bin */\n')
    f.write('static const u16 font_tiles[%d] = {\n' % len(words))
    for i in range(0, len(words), 16):
        f.write('    ' + ', '.join('0x%04X' % w for w in words[i:i + 16]) + ',\n')
    f.write('};\n')
