#!/usr/bin/env python3
"""The arcade's world map (the terrain the arcade's bg RAM is filled from), as C for terrain.c:
build/world.inc.

The arcade's world is 32 x 16 screens of 16 x 16 cells (512 columns, 256 rows, rows counted up from
the bottom), in gg5 (banked at $4000-$5FFF by $3E00):
  page 2 $4000 + (screen row << 5 | screen column): the screen's id (its stage-start pointer <$6C
         is this address, the restart entries' $4000 | y << 5 | x; the column / row writes step it:
         $81E7, $828E);
  page 2 $4200 + 2 x id: the base of the screen's blocks in page 1 ($4000/$4800/$5000/$5800);
  page 0 $4000 + $40 x id: 8 columns of 8 block numbers, bottom first ($82AA, $8262);
  page 1 base + 8 x block: a block is 2 x 2 cells, tiles at +0 + (column & 1) x 2 + (row & 1),
         attributes 4 bytes on.
The port's seven maps are this world's cells for their stages, byte for byte (all 34,816 cells);
the cells outside them (below stage 1-2's row 0, under stage 5's start, around stage 3's floor, ...)
come from here.

usage: mkworld.py <rom dir> <out.inc>"""
import os
import sys

romdir, dst = sys.argv[1], sys.argv[2]
gg5 = open(os.path.join(romdir, 'gg5.bin'), 'rb').read()
pg = [gg5[i * 0x2000:(i + 1) * 0x2000] for i in range(4)]
smap = pg[2][:512]
n = max(smap) + 1
base = []
for i in range(n):
    b = pg[2][0x200 + 2 * i] << 8 | pg[2][0x201 + 2 * i]
    assert b in (0x4000, 0x4800, 0x5000, 0x5800), hex(b)
    base.append(b - 0x4000)
scr = pg[0][:n * 64]


def arr(name, ctype, vals, per=16):
    out = ['static const %s %s[%d] WORLD = {' % (ctype, name, len(vals))]
    for i in range(0, len(vals), per):
        out.append('    ' + ', '.join('0x%02X' % v if ctype == 'u8' else '0x%04X' % v for v in vals[i:i + per]) + ',')
    out.append('};')
    return '\n'.join(out)


with open(dst, 'w') as f:
    f.write('/* generated by mkworld.py from gg5.bin: the arcade\'s world map */\n')
    f.write(arr('w_map', 'u8', smap) + '\n')
    f.write(arr('w_base', 'u16', base, 8) + '\n')
    f.write(arr('w_scr', 'u8', scr) + '\n')
    f.write(arr('w_blk', 'u8', pg[1]) + '\n')
