#!/usr/bin/env python3
"""Makaimura logo from the arcade char ROM (gg1.bin) -> Genesis tiles and maps.

The arcade keeps its logos 16 chars to a row (the English one, $5180 in bank
3, draws $100-$10F, $110-..., then $140-$144 and $170 beside them). The
Makaimura logo is 21 x 7: $180 + row*16 + col (16 x 7), $135 + row*16 + col
beside rows 0-3 (5 wide) and $13A + row*16 + col beside rows 4-5 (4 wide);
the two pieces placed where their edges meet the main block's (28/32 and
43/48 edge pixels, nothing else above 21). Pens as the arcade decodes them
(gng.py _char): 0 red, 1 light grey, 2 blue, 3 transparent (char palette 7).
Tiles are shared with flips; blank cells are 0.

   jp_tiles_menu / jp_map_menu: menus and title, pens 4-6 of the line used
       (map: flips | tile from the first, $FFFF blank)
   jp_tiles_game / jp_ovl_map: attract overlay (palette line 0 in stage 1:
       pens 3 red, $F light grey, $D blue), 7 rows of 32 from row 6 at col 5,
       in the 132 tiles free through the attract (the overlay's own 65 and 67
       more); the 3 tiles with the fewest pixels (flame specks) left out."""
import sys
src, dst = sys.argv[1], sys.argv[2]
d = open(src, 'rb').read()

W, H, COL = 21, 7, 5


def char(n):
    b = d[n * 16:(n + 1) * 16]
    return tuple(tuple(((b[y * 2 + x // 4] >> (3 - x % 4 + 4)) & 1) | (((b[y * 2 + x // 4] >> (3 - x % 4)) & 1) << 1)
                       for x in range(8)) for y in range(8))


layout = [[None] * W for _ in range(H)]
for r in range(7):
    for c in range(16):
        layout[r][c] = 0x180 + r * 16 + c
for r in range(4):
    for c in range(5):
        layout[r][16 + c] = 0x135 + r * 16 + c
for r in range(2):
    for c in range(4):
        layout[4 + r][16 + c] = 0x13A + r * 16 + c

BLANK = tuple(tuple(3 for _ in range(8)) for _ in range(8))
hflip = lambda t: tuple(row[::-1] for row in t)
vflip = lambda t: t[::-1]

uniq, cells = [], [[0] * W for _ in range(H)]     # cells: (index + 1) | flip bits << 11, 0 = blank
index = {}
for r in range(H):
    for c in range(W):
        if layout[r][c] is None:
            continue
        t = char(layout[r][c])
        if t == BLANK:
            continue
        for f, v in ((0, t), (1, hflip(t)), (2, vflip(t)), (3, hflip(vflip(t)))):
            if v in index:
                cells[r][c] = (f << 11) | (index[v] + 1)
                break
        else:
            index[t] = len(uniq)
            uniq.append(t)
            cells[r][c] = len(uniq)


def words(tiles, pen):
    out = []
    for t in tiles:
        for row in t:
            px = [pen[p] for p in row]
            out.append(px[0] << 12 | px[1] << 8 | px[2] << 4 | px[3])
            out.append(px[4] << 12 | px[5] << 8 | px[6] << 4 | px[7])
    return out


def emit(f, name, ws):
    f.write('static const u16 %s[%d] = {\n' % (name, len(ws)))
    for i in range(0, len(ws), 16):
        f.write('    ' + ', '.join('0x%04X' % w for w in ws[i:i + 16]) + ',\n')
    f.write('};\n')


# the attract slots: the overlay's three uploads ($11CE5C: 19, 36, 10 tiles), then the extra runs
SLOTS = list(range(0x2B8, 0x2CB)) + list(range(0x549, 0x56D)) + list(range(0x5F4, 0x5FE)) \
    + list(range(0x690, 0x6AA)) + list(range(0x6AB, 0x6C8)) + list(range(0x6D0, 0x6DC))
EXTRA = ((0x690, 26), (0x6AB, 29), (0x6D0, 12))
assert len(SLOTS) == 132
ink = lambda t: sum(p != 3 for row in t for p in row)
drop = set(sorted(range(len(uniq)), key=lambda i: ink(uniq[i]))[:len(uniq) - len(SLOTS)])
keep = [i for i in range(len(uniq)) if i not in drop]
slot_of = {i: SLOTS[k] for k, i in enumerate(keep)}

with open(dst, 'w') as f:
    f.write('/* generated by mkjp.py from rom/gg1.bin */\n')
    f.write('#define JP_W %d\n#define JP_H %d\n#define JP_NT %d\n' % (W, H, len(uniq)))
    emit(f, 'jp_tiles_menu', words(uniq, {0: 4, 1: 5, 2: 6, 3: 0}))
    # flips | tile from JP_TILE; $FFFF blank
    emit(f, 'jp_map_menu', [((v & 0x1800) | ((v & 0x7FF) - 1)) if v else 0xFFFF for row in cells for v in row])
    emit(f, 'jp_tiles_game', words([uniq[i] for i in keep], {0: 3, 1: 0xF, 2: 0xD, 3: 0}))
    m = []
    for r in range(H):
        for c in range(32):
            v = cells[r][c - COL] if COL <= c < COL + W else 0
            if v and (v & 0x7FF) - 1 in slot_of:
                m.append(0x8000 | (v & 0x1800) | slot_of[(v & 0x7FF) - 1])
            else:
                m.append(0)
    emit(f, 'jp_ovl_map', m)
    f.write('#define JP_OVL_EXTRA 65   /* tiles from here go to: */\n')
    f.write('static const u16 jp_ovl_extra[3][2] = { %s };\n'
            % ', '.join('{ 0x%03X, %d }' % e for e in EXTRA))
