#!/usr/bin/env python3
"""Makaimura logo (arcade char ROM gg1.bin, chars $180 + row*32 + col, 16x4)
-> two Genesis 4bpp tile sets:
   jp_tiles_menu: pens -> 1 face, 2 shade, 3 outline   (menu/title, own palette line)
   jp_tiles_game: pens -> $F, $B, $2 of the sprite line (attract overlay, line 0)
Tiles are in logo order: row-major, 16 per row."""
import sys
src, dst = sys.argv[1], sys.argv[2]
d = open(src, 'rb').read()
def tiles(penmap):
    words = []
    for r in range(4):
        for c in range(16):
            ch = 0x180 + r * 32 + c
            b = d[ch * 16:(ch + 1) * 16]
            for y in range(8):
                px = []
                for x in range(8):
                    byte = b[y * 2 + x // 4]; bit = 3 - (x % 4)
                    px.append(penmap[((byte >> bit) & 1) | (((byte >> (bit + 4)) & 1) << 1)])
                words.append((px[0] << 12) | (px[1] << 8) | (px[2] << 4) | px[3])
                words.append((px[4] << 12) | (px[5] << 8) | (px[6] << 4) | px[7])
    return words
def emit(f, name, words):
    f.write('static const u16 %s[%d] = {\n' % (name, len(words)))
    for i in range(0, len(words), 16):
        f.write('    ' + ', '.join('0x%04X' % w for w in words[i:i + 16]) + ',\n')
    f.write('};\n')
with open(dst, 'w') as f:
    f.write('/* generated by mkjp.py from rom/gg1.bin */\n')
    emit(f, 'jp_tiles_menu', tiles({3: 0, 1: 1, 2: 2, 0: 3}))
    # attract overlay: 64 logo tiles + 1 blank fill the game's 65 overlay slots
    # ($2B8-$2CA, $549-$56C, $5F4-$5FD), uploaded in three chunks of 19/36/10
    emit(f, 'jp_tiles_game', tiles({3: 0, 1: 0xF, 2: 0xB, 0: 0x2}) + [0] * 16)
    slot = lambda k: 0x2B8 + k if k < 19 else 0x549 + k - 19 if k < 55 else 0x5F4 + k - 55
    m = []
    for r in range(4):
        for c in range(32):
            m.append(0x8000 | slot(r * 16 + c - 8) if 8 <= c < 24 else 0)
    emit(f, 'jp_ovl_map', m)
