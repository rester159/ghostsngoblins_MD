"""Generates build/intro.inc (the SEGA and CAPCOM boot logos) from the intro
kits, which are not part of this repository.

usage: mkintro.py <out.inc>

Kit folders (defaults are relative to this file, override with env):
  SEGA_KIT    sega_intro_black background (Revenge of Shinobi logo)
  CHANT_KIT   sega_intro_white background (Sonic 1 "SE-GA" chant, raw PCM)
  CAPCOM_KIT  _capcom logo intro (SF2' SCE logo + FM jingle)

If any kit is missing, writes a stub without INTRO_HAVE and the boot
skips the intros.
"""
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
SEGA = os.environ.get('SEGA_KIT', os.path.join(here, '../../../__genesis assets/sega_intro_black background'))
CHANT = os.environ.get('CHANT_KIT', os.path.join(here, '../../../__genesis assets/sega_intro_white background'))
CAPCOM = os.environ.get('CAPCOM_KIT', os.path.join(here, '../../_capcom logo intro'))

# (kit file, array name in the kit, type, name here)
ARRAYS = [
    (os.path.join(SEGA, 'sega_logo_shinobi.c'), 'sheen_wave', 'u16', 'sega_wave'),
    (os.path.join(SEGA, 'sega_logo_shinobi.c'), 'base_pal', 'u16', 'sega_pal'),
    (os.path.join(SEGA, 'sega_logo_shinobi.c'), 'shinobi_logo_tiles', 'u32', 'sega_tiles'),
    (os.path.join(CAPCOM, 'capcom_logo.c'), 'capcom_logo_tiles', 'u32', 'capcom_tiles'),
    (os.path.join(CAPCOM, 'capcom_logo.c'), 'base_pal', 'u16', 'capcom_pal'),
    (os.path.join(CAPCOM, 'capcom_logo.c'), 'glint_pal', 'u16', 'capcom_glint'),
    (os.path.join(CAPCOM, 'capcom_logo.c'), 'glint_t', 'u16', 'capcom_glint_t'),
    (os.path.join(CAPCOM, 'capcom_logo.c'), 'jingle_setup', 'u8', 'capcom_setup'),
    (os.path.join(CAPCOM, 'capcom_logo.c'), 'jingle_ev', 'u8', 'capcom_ev'),
]


def array(src, name):
    m = re.search(r'\b%s\s*\[[^\]]*\]\s*=\s*\{(.*?)\};' % name, src, re.S)
    if not m:
        raise SystemExit('mkintro: %s not found' % name)
    return [int(v, 0) for v in re.findall(r'0x[0-9A-Fa-f]+|\d+', m.group(1))]


def main(out):
    lines = ['/* GENERATED by mkintro.py from the SEGA and CAPCOM intro kits. */']
    pcm = os.path.join(CHANT, 'sega_chant.pcm')        # unsigned 8-bit, 16 kHz
    if all(os.path.exists(f) for f, _, _, _ in ARRAYS) and os.path.exists(pcm):
        lines.append('#define INTRO_HAVE 1')
        for f, name, typ, mine in ARRAYS:
            v = array(open(f).read(), name)
            lines.append('static const %s %s[%d] = {' % (typ, mine, len(v)))
            w = {'u8': 2, 'u16': 4, 'u32': 8}[typ]
            for i in range(0, len(v), 16):
                lines.append('    ' + ', '.join('0x%0*X' % (w, x) for x in v[i:i + 16]) + ',')
            lines.append('};')
        v = open(pcm, 'rb').read()
        # one 32 KiB Z80 bank window holds the whole sample
        lines.append('static const u8 sega_chant[%d] __attribute__((aligned(0x8000))) = {' % len(v))
        for i in range(0, len(v), 16):
            lines.append('    ' + ', '.join('0x%02X' % x for x in v[i:i + 16]) + ',')
        lines.append('};')
    else:
        print('mkintro: intro kits not found, building without the SEGA/CAPCOM intros')
    open(out, 'w').write('\n'.join(lines) + '\n')


main(sys.argv[1])
