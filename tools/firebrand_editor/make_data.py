"""Build firebrand_data.js for the Firebrand pixel editor.

Sources: the ROM (Arthur's frames, the game's Red Arremer), art/firebrand
(the in-game Firebrand bank + flags, see art/firebrand/src/build.py) and the
Arthur animations recorded headless (tools/maximo_editor/maximo_data.js), mapped
to Firebrand's bank the way src_patch/firebrand.c shows them.

usage: make_data.py <rom (fixed build)>
"""
import base64
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', '..')
sys.path.insert(0, os.path.join(ROOT, 'art', 'firebrand', 'src'))
import arremer                                   # noqa: E402

FRAMES = 112
FB_WALK, FB_FLY, FB_CLING = 84, 96, 108          # firebrand.c
F_PAL2, F_RUN, F_FACES_LEFT = 4, 8, 16
# palette lines 0 and 2 in play (read from CRAM, the same in every stage-1 frame)
LINE0 = [(0, 0, 0), (0, 0, 0), (116, 0, 0), (206, 0, 0), (87, 52, 0), (144, 52, 0), (116, 87, 0),
         (206, 116, 0), (144, 144, 0), (52, 52, 116), (172, 144, 116), (116, 116, 144),
         (206, 172, 144), (0, 116, 172), (144, 144, 172), (172, 172, 206)]
LINE2 = [(0, 0, 0), (0, 0, 0), (52, 52, 0), (116, 52, 0), (0, 87, 0), (144, 87, 0), (52, 116, 0),
         (87, 116, 0), (144, 172, 0), (52, 52, 52), (144, 116, 52), (87, 144, 52), (116, 87, 87),
         (116, 116, 116), (144, 116, 116), (144, 0, 0)]
ARREMER_LINE2 = set(range(51, 61)) | {70}        # star, flames, score: the rest is line 0


def slot_of(i):
    """Maximo-editor frame index (A0..A10, B0..B64) -> Firebrand bank slot.
    In play Arthur's frames stream from $40000 + 0x200k and Firebrand's bank
    slot is 11 + k (A5/A6 replay A3/A2, A10 is $41000)."""
    if i < 0:
        return -1
    if i < 11:
        return 11 + [0, 1, 2, 3, 4, 3, 2, 5, 6, 7, 8][i]
    return 19 + (i - 11)


def fb_anim(seq, flags, loop):
    """Apply firebrand.c's walk-cycle substitution (7 ticks a frame, 42-tick cycle)."""
    if loop and any(s >= 0 and flags[s] & F_RUN for s, _ in seq):
        seq = (seq * 7)[:126]                    # lcm of Arthur's 18-tick walk and 42
    out, walk_t = [], 0
    for s, dy in seq:
        if s >= 0 and flags[s] & F_RUN:
            walk_t = (walk_t + 1) % 42
            s = FB_WALK + (6 if flags[s] & F_FACES_LEFT else 0) + walk_t // 7
        out.append([s, dy])
    return out


def main(rom_path):
    rom = open(rom_path, 'rb').read()
    art = os.path.join(ROOT, 'art', 'firebrand')
    bank = open(os.path.join(art, 'firebrand_bank.bin'), 'rb').read()
    flags = open(os.path.join(art, 'firebrand_flags.bin'), 'rb').read()
    assert len(bank) == FRAMES * 0x300 and len(flags) == FRAMES
    arthur = rom[0x109E2:0x109E2 + 11 * 0x200] + rom[0x40000:0x40000 + 73 * 0x200]
    arr = bytearray()
    for k in range(71):
        g = arremer.frame(rom, k)
        for row in g:
            for x in range(0, 48, 2):
                arr.append(row[x] << 4 | row[x + 1])
    src = open(os.path.join(ROOT, 'tools', 'maximo_editor', 'maximo_data.js')).read()
    anims = json.loads(re.search(r'anims:(\[.*\])\n', src).group(1))
    out = []
    for a in anims:
        if a['group'] == 'Armor' or 'Armor' in a['name'] or a['name'].startswith('Armor'):
            continue                             # Firebrand is never armored
        group = {'Boxer': 'Moves'}.get(a['group'], a['group'])
        name = a['name'].replace('Boxer ', '')
        seq = [[slot_of(f), dy] for f, dy in a['f']]
        out.append({'group': group, 'name': name, 'loop': a['loop'], 'f': fb_anim(seq, flags, a['loop'])})
    for side, left in (('right', 0), ('left', 6)):
        out.append({'group': 'Hover', 'name': f'Hover ({side})', 'loop': True,
                    'f': [[FB_FLY + left + t // 6, 0] for t in range(36)]})
    # on a wall: holding still, then a shot (firebrand.c shows the firing pose
    # for CLING_FIRE = 15 frames after each throw)
    hold = 15
    for side, left in (('right', 0), ('left', 1)):
        out.append({'group': 'Wall', 'name': f'Cling ({side})', 'loop': True,
                    'f': [[FB_CLING + left, 0]] * 30})
        out.append({'group': 'Wall', 'name': f'Cling and fire ({side})', 'loop': True,
                    'f': [[FB_CLING + left, 0]] * 20 + [[FB_CLING + 2 + left, 0]] * hold})
    b = lambda x: base64.b64encode(bytes(x)).decode()
    js = ("// Generated by make_data.py: in-game Firebrand (art/firebrand), Arthur's frames per\n"
          "// slot, the game's Red Arremer (71 frames, 48x32, 4bpp rows) and animations\n"
          "// ([slot, dy] at 60 fps; slot -1 = hidden).\n"
          "window.FIREBRAND_DATA={\n"
          f"  line0:{json.dumps(LINE0)},\n  line2:{json.dumps(LINE2)},\n"
          f"  bank:'{b(bank)}',\n  flags:'{b(flags)}',\n  arthur:'{b(arthur)}',\n"
          f"  arremer:'{b(arr)}',\n  arremerLine2:{json.dumps(sorted(ARREMER_LINE2))},\n"
          f"  anims:{json.dumps(out, separators=(',', ':'))}\n}};\n")
    open(os.path.join(HERE, 'firebrand_data.js'), 'w').write(js)
    print('anims', len(out), 'bytes', len(js))


if __name__ == '__main__':
    main(sys.argv[1])
